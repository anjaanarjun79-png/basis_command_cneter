export const loadStoredSettings = (): UserSettings => {
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.SETTINGS);
    return raw ? { ...defaultSettings, ...JSON.parse(raw) } : defaultSettings;
  } catch (e) {
    return defaultSettings;
  }
};

export const saveStoredSettings = (settings: UserSettings) => {
  try {
    localStorage.setItem(STORAGE_KEYS.SETTINGS, JSON.stringify(settings));
  } catch (e) {
    console.error('Failed to save settings', e);
  }
};

export const exportAllDataJSON = () => {
  const exportPayload = {
    version: '1.0',
    exportedAt: new Date().toISOString(),
    progress: loadStoredProgress(),
    reports: loadStoredReports(),
    settings: loadStoredSettings(),
    weeklyNotes: localStorage.getItem(STORAGE_KEYS.WEEKLY_NOTES)
      ? JSON.parse(localStorage.getItem(STORAGE_KEYS.WEEKLY_NOTES)!)
      : {},
  };
  return JSON.stringify(exportPayload, null, 2);
};

export const importAllDataJSON = (jsonString: string): { success: boolean; error?: string } => {
  try {
    const data = JSON.parse(jsonString);
    if (!data || typeof data !== 'object') {
      return { success: false, error: 'Invalid JSON payload structure' };
    }
    if (data.progress) localStorage.setItem(STORAGE_KEYS.PROGRESS, JSON.stringify(data.progress));
    if (data.reports) localStorage.setItem(STORAGE_KEYS.REPORTS, JSON.stringify(data.reports));
    if (data.settings) localStorage.setItem(STORAGE_KEYS.SETTINGS, JSON.stringify(data.settings));
    if (data.weeklyNotes) localStorage.setItem(STORAGE_KEYS.WEEKLY_NOTES, JSON.stringify(data.weeklyNotes));
    return { success: true };
  } catch (err: any) {
    return { success: false, error: err?.message || 'Failed to parse JSON backup' };
  }
};

export const resetAllProgress = () => {
  localStorage.removeItem(STORAGE_KEYS.PROGRESS);
  localStorage.removeItem(STORAGE_KEYS.WEEKLY_NOTES);
  localStorage.removeItem(STORAGE_KEYS.LAB_HISTORY);
  localStorage.removeItem(STORAGE_KEYS.QUIZ_HISTORY);
};
